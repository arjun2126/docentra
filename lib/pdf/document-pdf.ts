import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

import type { DocumentDto } from "@/lib/docflow/documents";

/**
 * The layout model is pure data, so the arithmetic and ordering can be tested
 * without rendering a PDF byte stream.
 */
export type PdfModel = {
  title: string;
  subtitle: string[];
  columns: string[];
  rows: string[][];
  total: string;
  footer: string;
};

export type PdfRow = { cells: string[]; widths: number[] };

const COLUMNS = ["#", "Item", "Quantity", "Price", "Amount"];
const WIDTHS = [28, 250, 70, 80, 90];

/** pdf-lib standard fonts are WinAnsi; everything else would throw. */
function toWinAnsi(value: string): string {
  return value
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/[\u2013\u2014]/g, "-")
    .replace(/\u00B7/g, "-")
    .replace(/[^\x20-\x7E]/g, "?");
}

export function buildDocumentPdfModel(document: DocumentDto): PdfModel {
  return {
    title: `Document ${toWinAnsi(document.documentNumber)}`,
    subtitle: [
      `Vendor: ${toWinAnsi(document.vendor.name)} (${toWinAnsi(document.vendor.code)})`,
      `Date: ${document.documentDate}`,
      `Status: ${document.status}`,
    ],
    columns: COLUMNS,
    rows: document.lines.map((line) => [
      String(line.lineNo),
      toWinAnsi(line.item),
      line.quantity,
      line.price,
      line.amount,
    ]),
    total: document.totalAmount,
    footer: "Generated by Docentra DocFlow. Amounts are unformatted numbers.",
  };
}

export function rowWidths(): number[] {
  return [...WIDTHS];
}

/** Render the model. Amounts are taken from the model, never recomputed here. */
export async function renderDocumentPdf(model: PdfModel): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);

  const pageWidth = 595;
  const pageHeight = 842;
  const margin = 48;
  let page = pdf.addPage([pageWidth, pageHeight]);
  let y = pageHeight - margin;

  const drawRow = (cells: string[], size: number, useBold: boolean) => {
    let x = margin;
    cells.forEach((cell, index) => {
      page.drawText(cell.slice(0, 60), {
        x,
        y,
        size,
        font: useBold ? bold : font,
        color: rgb(0.1, 0.1, 0.12),
      });
      x += WIDTHS[index] ?? 80;
    });
  };

  const newPageIfNeeded = () => {
    if (y < margin + 60) {
      page = pdf.addPage([pageWidth, pageHeight]);
      y = pageHeight - margin;
    }
  };

  page.drawText(toWinAnsi(model.title), { x: margin, y, size: 18, font: bold });
  y -= 26;
  for (const line of model.subtitle) {
    page.drawText(toWinAnsi(line), { x: margin, y, size: 10, font, color: rgb(0.35, 0.35, 0.4) });
    y -= 14;
  }

  y -= 12;
  drawRow(model.columns, 9, true);
  y -= 6;
  page.drawLine({
    start: { x: margin, y },
    end: { x: pageWidth - margin, y },
    thickness: 0.5,
    color: rgb(0.75, 0.75, 0.8),
  });
  y -= 14;

  for (const row of model.rows) {
    newPageIfNeeded();
    drawRow(row, 10, false);
    y -= 16;
  }

  newPageIfNeeded();
  y -= 6;
  page.drawLine({
    start: { x: margin, y },
    end: { x: pageWidth - margin, y },
    thickness: 0.5,
    color: rgb(0.75, 0.75, 0.8),
  });
  y -= 18;
  page.drawText(`Total: ${model.total}`, { x: pageWidth - margin - 160, y, size: 12, font: bold });

  page.drawText(toWinAnsi(model.footer), {
    x: margin,
    y: margin / 2,
    size: 8,
    font,
    color: rgb(0.45, 0.45, 0.5),
  });

  return pdf.save();
}
